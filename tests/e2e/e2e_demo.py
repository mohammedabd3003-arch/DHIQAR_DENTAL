def setup(ctx):
  ctx.route('**/leaflet.min.js', lambda r: r.fulfill(path='mockL.js', content_type='text/javascript'))
  ctx.route('**/leaflet.min.css', lambda r: r.fulfill(body='', content_type='text/css'))
  ctx.route('**/qrcode.min.js', lambda r: r.fulfill(path='mockQR.js', content_type='text/javascript'))
